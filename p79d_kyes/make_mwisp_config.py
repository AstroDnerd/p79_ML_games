"""
make_mwisp_config.py
====================
Build obs_mwisp.json (the predict_observations_net9010.py cloud list) from the
MWISP DR1 cloud sample in observations/mwips/clouds_q2_CO (l = 105-150 deg,
|b| < 5 deg; DBSCAN clouds, 2-sigma masked cubes, 30" pixels, 0.166 km/s).

Selection: 13CO angular area >= --min_area arcmin^2 (a 128-pixel tile is
64' x 64' = 4096 arcmin^2 before any regridding).

Distances are kinematic, from a flat rotation curve (R0 = 8.15 kpc,
Theta0 = 236 km/s; Reid et al. 2019). In the second quadrant there is no
near/far ambiguity, but clouds with V_lsr > -10 km/s (the Local arm) have
distances dominated by peculiar motions: they get the placeholder
--local_pc and distance_method "local placeholder". Perseus-arm streaming
(~ -15 km/s) makes the kinematic distances too large by up to ~1 kpc. The
distance only sets the tile size in pc (tile_pc); the network inputs do not
depend on it.

  python make_mwisp_config.py                  # -> obs_mwisp.json
"""
import argparse, json, os
import numpy as np
import pandas as pd

p = argparse.ArgumentParser()
p.add_argument("--mwisp_dir", default="/home/x-nbisht1/projects/p79d_dataset/observations/mwips/clouds_q2_CO")
p.add_argument("--min_area", type=float, default=400.0, help="13CO angular area, arcmin^2")
p.add_argument("--local_pc", type=float, default=500.0)
p.add_argument("--out", default="obs_mwisp.json")
args = p.parse_args()

R0, TH0 = 8.15, 236.0
TILE_ARCMIN2 = 64.0**2


def kinematic_kpc(l_deg, b_deg, v):
    """Distance for a flat rotation curve; NaN where V_lsr has no solution (l in 90-180, V > 0)."""
    sl, cl = np.sin(np.radians(l_deg)), np.cos(np.radians(l_deg))
    R = R0 / (1.0 + v / (TH0 * sl * np.cos(np.radians(b_deg))))
    disc = R**2 - (R0 * sl)**2
    d = R0 * cl + np.sqrt(np.where(disc > 0, disc, np.nan))
    return np.where((R > 0) & (d > 0), d, np.nan)


t = pd.read_csv(os.path.join(args.mwisp_dir, "clouds_13co/clouds_13co_table.csv"))
t.columns = [c.strip() for c in t.columns]
t = t[t["Angular area (13CO)"] >= args.min_area].sort_values("Angular area (13CO)", ascending=False)

clouds = {}
for _, r in t.iterrows():
    cid = int(r["ID"])
    f13 = f"clouds_13co/clouds_13co_fits/cloud{cid}cube_13CO_dbscan_2sigma.fits"
    f12 = f"clouds_12co/clouds_12co_fits/cloud{cid}cube_12CO_dbscan_2sigma.fits"
    if not (os.path.exists(os.path.join(args.mwisp_dir, f13)) and os.path.exists(os.path.join(args.mwisp_dir, f12))):
        continue
    v = float(r["V_cen"])
    d = float(kinematic_kpc(float(r["l_cen"]), float(r["b_cen"]), v)) * 1e3
    local = v > -10.0 or not np.isfinite(d)
    area = float(r["Angular area (13CO)"])
    clouds[r["Name"].strip()] = {
        "fits": {"13co": f13, "12co": f12},
        "tracer": "13CO(1-0)", "telescope": "PMO 13.7m (MWISP DR1)",
        "beam_arcsec": 50.0,
        "distance_pc": args.local_pc if local else round(d, 0),
        "distance_method": "local placeholder" if local else "kinematic (flat curve, Reid+2019)",
        "T_K": 10.0,
        "noise_rms_K": {"13co": 0.25, "12co": 0.47},
        "n_tiles": int(min(6, max(1, round(area / (0.3 * TILE_ARCMIN2))))),
        "min_coverage": 0.1, "max_overlap": 0.1,
        "mwisp_id": cid, "l_cen": float(r["l_cen"]), "b_cen": float(r["b_cen"]), "V_cen": v,
        "area_13co_arcmin2": area, "area_12co_arcmin2": float(r["Angular area (12CO)"]),
        "Ms_literature": None, "Ms_literature_ref": None,
    }

cfg = {
    "description": ("MWISP DR1 clouds (l = 105-150 deg) for net9010, generated by make_mwisp_config.py. "
                    "Each cloud has 13CO and 12CO DBSCAN cubes (2-sigma masked, zero elsewhere); the DR1 noise "
                    "(0.25 K 13CO, 0.47 K 12CO) replaces the edge-channel estimate."),
    "obs_dir": args.mwisp_dir,
    "output_dir": "/home/x-nbisht1/plots/observations_net9010_mwisp",
    "mu_sound": 2.33, "mask_sigma": 3.0, "min_channels": "auto", "tile_size": 128,
    "clouds": clouds,
    "notes": {"selection": f"13CO area >= {args.min_area} arcmin^2: {len(clouds)} clouds",
              "distances": "kinematic, flat rotation curve R0 = 8.15 kpc, Theta0 = 236 km/s; V_lsr > -10 km/s -> "
                           f"{args.local_pc} pc placeholder (Local arm); only tile_pc depends on it",
              "beam": "MWISP HPBW ~50 arcsec at 115 GHz (52 arcsec at 110 GHz), 30 arcsec pixels",
              "source": "MWISP DR1 (arXiv 2512.08260; ScienceDB doi 10.57760/sciencedb.27351)"},
}
json.dump(cfg, open(args.out, "w"), indent=2)
n_local = sum(c["distance_method"] != "kinematic (flat curve, Reid+2019)" for c in clouds.values())
print(f"{args.out}: {len(clouds)} clouds ({n_local} local placeholders); distances "
      f"{np.percentile([c['distance_pc'] for c in clouds.values()], [0, 50, 100])} pc")
